#!/usr/bin/env bash
# Downloads CS2 map screenshots (the in-game map-select thumbnails) once, shrinks them to
# 480px WebP in public/maps/, and writes app/utils/map-images.generated.ts.
# The portal then serves them locally – no internet needed at the LAN.
#
# Source: https://github.com/MurkyYT/cs2-map-icons (auto-extracted from the CS2 depot).
# The images are © Valve Corporation; used here for a private, non-commercial LAN page.
#
# Usage: bash scripts/fetch-map-images.sh     (needs curl, python3, vips)
set -euo pipefail
export VIPS_WARNING=0  # silence warnings about optional vips modules

cd "$(dirname "$0")/.."
REPO=MurkyYT/cs2-map-icons
OUT=public/maps
GEN=app/utils/map-images.generated.ts
TMP=$(mktemp -d)
trap 'rm -rf "$TMP"' EXIT

mkdir -p "$OUT"

# All images/thumbs/<map>_png.png (skip the numbered alternates and non-maps).
maps=$(curl -fsSL "https://api.github.com/repos/$REPO/git/trees/main?recursive=1" | python3 -c '
import json, re, sys
tree = json.load(sys.stdin)["tree"]
skip = {"lobby_mapveto", "random"}
for x in tree:
    m = re.fullmatch(r"images/thumbs/([a-z0-9_]+)_png\.png", x["path"])
    if m and not re.search(r"_\d$", m.group(1)) and m.group(1) not in skip and not m.group(1).startswith("rush_"):
        print(m.group(1))
')

ok=()
for map in $maps; do
  src="$TMP/$map.png"
  if curl -fsSL -o "$src" "https://raw.githubusercontent.com/$REPO/main/images/thumbs/${map}_png.png"; then
    vips thumbnail "$src" "$OUT/$map.webp[Q=78,strip]" 480
    ok+=("$map")
    echo "  ✓ $map"
  else
    echo "  ✗ $map (download failed)" >&2
  fi
done

{
  echo '// Generated by scripts/fetch-map-images.sh – do not edit.'
  echo '// Maps with a local screenshot in public/maps/<name>.webp'
  echo 'export const MAP_IMAGES: ReadonlySet<string> = new Set(['
  for m in "${ok[@]}"; do echo "  '$m',"; done
  echo '])'
} > "$GEN"

echo "Saved ${#ok[@]} images to $OUT ($(du -sh "$OUT" | cut -f1)), wrote $GEN"
